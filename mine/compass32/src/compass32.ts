// UPPER_BOUNDS: 隣り合う方位角（代表角度）の中間角（平均値）を境界のしきい値として定義した配列。
// 角度 degrees が UPPER_BOUNDS[i] 未満の場合に、そのインデックス i を判定結果として返します。
// （例: UPPER_BOUNDS[0] (7.018°) = (0.000° + 14.036°) / 2）
const UPPER_BOUNDS: number[] = [
    7.018, 20.301, 31.718, 40.935, 49.065, 58.282, 69.699, 82.982,
    97.018, 110.301, 121.718, 130.935, 139.065, 148.282, 159.699, 172.982,
    187.018, 200.301, 211.718, 220.935, 229.065, 238.282, 250.699, 262.982,
    277.018, 290.301, 301.718, 310.935, 319.065, 328.282, 339.699, 352.982
];

export function getDirectionIndex(degrees: number): number {
    let norm = degrees % 360;
    if (norm < 0) {
        norm += 360;
    }
    for (let i = 0; i < UPPER_BOUNDS.length; i++) {
        if (norm < UPPER_BOUNDS[i]) {
            return i;
        }
    }
    return 0;
}

export function getDirectionPoints(degrees: number): Point[] {
    const idx = getDirectionIndex(degrees);
    const packed = DIRECTION_POINTS[idx];
    const points: Point[] = [];
    for (let i = 0; i < packed.length; i++) {
        const val = packed[i];
        points.push({
            x: Math.floor(val / 10),
            y: val % 10
        });
    }
    return points;
}
